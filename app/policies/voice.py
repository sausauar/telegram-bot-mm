from __future__ import annotations


SOURCE_STYLE_REPLACEMENTS = (
    ("Компания заявляет", "Мы заявляем"),
    ("компания заявляет", "мы заявляем"),
    ("Компания предлагает", "Мы предлагаем"),
    ("компания предлагает", "мы предлагаем"),
    ("Компания помогает", "Мы помогаем"),
    ("компания помогает", "мы помогаем"),
    ("Компания работает", "Мы работаем"),
    ("компания работает", "мы работаем"),
    ("На сайте указано, что ", ""),
    ("на сайте указано, что ", ""),
    ("На сайте указаны", "У нас указаны"),
    ("на сайте указаны", "у нас указаны"),
    ("В базе знаний указано, что ", ""),
    ("в базе знаний указано, что ", ""),
    ("В базе знаний", "В информации Centr Krasok"),
    ("в базе знаний", "в информации Centr Krasok"),
    ("По данным компании:", "Кратко:"),
    ("по данным компании:", "кратко:"),
)


def apply_company_voice(text: str) -> str:
    polished = text
    for old, new in SOURCE_STYLE_REPLACEMENTS:
        polished = polished.replace(old, new)
    return polished.strip()

